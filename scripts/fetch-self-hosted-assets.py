"""Download the third-party assets the site serves from its own origin.

Run from the website root:  python scripts/fetch-self-hosted-assets.py [fonts] [fontawesome] [thumbs]

Why: loading fonts, icons or YouTube thumbnails from Google/Cloudflare sends every
visitor's IP address to those companies before any consent. Serving the files
from kiflowstate.de avoids that. Re-run `thumbs` after adding a video to js/videos.js.
"""
import io, json, os, re, subprocess, sys, urllib.request

UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"
FONT_CSS = ("https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500"
            "&family=Schibsted+Grotesk:ital,wght@0,400;0,500;0,600;0,700;1,600"
            "&family=DM+Sans:wght@400;500;600;700&display=swap")
KEEP_SUBSETS = {"latin", "latin-ext"}
FA_VERSION = "6.5.2"
FA_BASE = f"https://cdnjs.cloudflare.com/ajax/libs/font-awesome/{FA_VERSION}"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def fonts():
    css = get(FONT_CSS).decode("utf-8")
    blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]+\})", css)
    out, seen = [], {}
    for subset, block in blocks:
        if subset not in KEEP_SUBSETS:
            continue
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        style = re.search(r"font-style:\s*(\w+)", block).group(1)
        if url not in seen:
            weight = re.search(r"font-weight:\s*([\d ]+)", block).group(1).strip().replace(" ", "-")
            name = f"{family.lower().replace(' ', '-')}-{style}-{weight}-{subset}.woff2"
            n = 2
            while name in seen.values():
                name = name.replace(".woff2", f"-{n}.woff2"); n += 1
            write(os.path.join("fonts", name), get(url))
            seen[url] = name
        out.append(f"/* {subset} */\n" + block.replace(url, f"../fonts/{seen[url]}"))
    header = ("/* Self-hosted fonts (SIL Open Font License 1.1): Schibsted Grotesk, IBM Plex Mono, DM Sans.\n"
              "   Generated by scripts/fetch-self-hosted-assets.py. No request leaves kiflowstate.de. */\n")
    write("css/fonts.css", (header + "\n".join(out) + "\n").encode("utf-8"))
    print(f"fonts: {len(seen)} files, {len(out)} @font-face rules")


def fontawesome():
    css = get(f"{FA_BASE}/css/all.min.css").decode("utf-8")
    # Keep only woff2 sources; every supported browser uses them and the ttf fallbacks are never fetched.
    css = re.sub(r',\s*url\(\.\./webfonts/[\w.-]+\.ttf\)\s*format\("truetype"\)', "", css)
    files = sorted(set(re.findall(r"\.\./webfonts/([\w.-]+\.woff2)", css)))
    for name in files:
        write(os.path.join("css/vendor/fontawesome/webfonts", name), get(f"{FA_BASE}/webfonts/{name}"))
    write("css/vendor/fontawesome/css/all.min.css", css.encode("utf-8"))
    write("css/vendor/fontawesome/LICENSE.txt", get(f"https://raw.githubusercontent.com/FortAwesome/Font-Awesome/{FA_VERSION}/LICENSE.txt"))
    print("fontawesome:", ", ".join(files))


def thumbs():
    from PIL import Image
    js = ("const fs=require('fs');const V=new Function(fs.readFileSync('js/videos.js','utf8')+';return VIDEOS')();"
          "const ids=new Set();const add=(x)=>{if(typeof x==='string'&&/^[A-Za-z0-9_-]{11}$/.test(x))ids.add(x)};"
          "for(const v of V){add(v.youtubeId);if(!v.youtubeId&&!v.series)add(v.id);for(const p of v.parts||[])add(p.youtubeId)}"
          "console.log(JSON.stringify([...ids]))")
    ids = json.loads(subprocess.check_output(["node", "-e", js]).decode())
    made = 0
    for vid in ids:
        big, small = f"images/yt/{vid}.jpg", f"images/yt/{vid}-sm.jpg"
        if os.path.exists(big) and os.path.exists(small):
            continue
        data = None
        for variant in ("maxresdefault", "sddefault", "hqdefault"):
            try:
                data = get(f"https://i.ytimg.com/vi/{vid}/{variant}.jpg"); break
            except Exception:
                continue
        if not data:
            print("thumbs: no image for", vid); continue
        im = Image.open(io.BytesIO(data)).convert("RGB")
        w, h = im.size
        if abs(w / h - 16 / 9) > 0.02:  # 4:3 variants carry black bars: crop to 16:9
            nh = round(w * 9 / 16); top = (h - nh) // 2
            im = im.crop((0, top, w, top + nh))
        os.makedirs("images/yt", exist_ok=True)
        im.resize((1280, 720), Image.LANCZOS).save(big, quality=82, optimize=True, progressive=True)
        im.resize((320, 180), Image.LANCZOS).save(small, quality=80, optimize=True)
        made += 1
    print(f"thumbs: {len(ids)} videos, {made} new")


if __name__ == "__main__":
    todo = sys.argv[1:] or ["fonts", "fontawesome", "thumbs"]
    for name in todo:
        {"fonts": fonts, "fontawesome": fontawesome, "thumbs": thumbs}[name]()
